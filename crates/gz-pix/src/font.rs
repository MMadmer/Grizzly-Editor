//! The built-in face: 5 x 7 dots, ASCII 0x20..=0x7E, drawn in whole multiples of a dot.
//!
//! A picture an agent reads back needs digits and names that are the same on every machine and
//! at every size, without a font file or a window: a dot matrix is exactly that.

/// Dots across a glyph.
pub const GLYPH_W: u32 = 5;
/// Dots down a glyph.
pub const GLYPH_H: u32 = 7;
/// Dots from one glyph's left edge to the next one's.
pub const ADVANCE: u32 = GLYPH_W + 1;
/// Dots from one line's top to the next one's.
pub const LINE: u32 = GLYPH_H + 2;

/// One glyph: five columns left to right, bit 0 the top dot.
type Glyph = [u8; 5];

