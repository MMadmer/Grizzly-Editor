/// The glyph of a character; one the face lacks is drawn as `?`.
pub(crate) fn glyph(c: char) -> &'static Glyph {
    let i = match c {
        ' '..='~' => c as usize - 0x20,
        _ => '?' as usize - 0x20,
    };
    &GLYPHS[i]
}

/// Whether the dot at `col`, `row` of a glyph is set.
pub(crate) fn dot(g: &Glyph, col: u32, row: u32) -> bool {
    col < GLYPH_W && row < GLYPH_H && g[col as usize] >> row & 1 == 1
}

/// The width and height in pixels of one line of text drawn at `scale`.
pub fn text_size(text: &str, scale: u32) -> (u32, u32) {
    let n = text.chars().count() as u32;
    let scale = scale.max(1);
    (if n == 0 { 0 } else { (n * ADVANCE - 1) * scale }, GLYPH_H * scale)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_character_has_dots_and_the_rest_are_a_question_mark() {
        for c in '!'..='~' {
            let g = glyph(c);
            assert!(g.iter().any(|col| *col != 0), "{c:?} is empty");
            // seven rows: bit 7 is never set
            assert!(g.iter().all(|col| col & 0x80 == 0), "{c:?} is taller than the face");
        }
        assert!(glyph(' ').iter().all(|col| *col == 0));
        assert_eq!(glyph('\u{0416}'), glyph('?'));
        assert_eq!(glyph('\n'), glyph('?'));
    }

    #[test]
    fn digits_are_all_different() {
        let digits: Vec<_> = ('0'..='9').map(glyph).collect();
        for (i, a) in digits.iter().enumerate() {
            for b in &digits[i + 1..] {
                assert_ne!(a, b);
            }
        }
    }

    #[test]
    fn a_line_is_as_wide_as_its_characters() {
        assert_eq!(text_size("", 2), (0, 14));
        assert_eq!(text_size("1", 1), (5, 7));
        assert_eq!(text_size("12", 1), (11, 7));
        assert_eq!(text_size("12", 3), (33, 21));
        // a scale of nothing is one
        assert_eq!(text_size("1", 0), (5, 7));
    }
}
